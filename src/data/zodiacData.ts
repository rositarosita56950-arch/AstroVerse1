export function getZodiacByDate(month: number, day: number): ZodiacSign {
  for (const sign of ZODIAC_SIGNS) {
    if (sign.startMonth === month && day >= sign.startDay) return sign;
    if (sign.endMonth === month && day <= sign.endDay) return sign;
  }
  // Fallback
  return ZODIAC_SIGNS[0];
}

export function getZodiacById(id: string): ZodiacSign {
  return ZODIAC_SIGNS.find((z) => z.id.toLowerCase() === id.toLowerCase()) || ZODIAC_SIGNS[0];
}
